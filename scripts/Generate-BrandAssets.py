"""Export the supplied SVG brand artwork to WPF vectors and Windows icon formats.

Generated assets are committed with the app; Python is not needed to build or run it.
The source SVGs remain unchanged. Requires CairoSVG and Pillow only for regeneration.
"""
from io import BytesIO
from pathlib import Path
from xml.sax.saxutils import quoteattr
import xml.etree.ElementTree as ET

import cairosvg
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src/WindowSocks.Desktop/Assets/Brand"
SVG = "http://www.w3.org/2000/svg"
FILES = {
    "XiaomaoMark": "logo-mono-dark-mark-crop.svg",
    "XiaomaoSquare": "logo-mono-dark-app-square.svg",
    "XiaomaoFull": "logo-mono-dark-full-crop.svg",
}


def vector(key, source):
    root = ET.parse(source).getroot()
    # These supplied variants contain only untransformed paths with a uniform color.
    # Reject changed artwork rather than silently losing new SVG features.
    allowed = {"svg", "defs", "style", "linearGradient", "stop", "g", "path"}
    for node in root.iter():
        if node.tag.rsplit("}", 1)[-1] not in allowed or "transform" in node.attrib:
            raise ValueError("Unsupported SVG feature; review the brand export.")
    colors = {node.get("stop-color") for node in root.iter(f"{{{SVG}}}stop")}
    if colors != {"#111827"}:
        raise ValueError("The source is no longer the supplied uniform dark artwork.")
    x, y, width, height = map(float, root.get("viewBox").split())
    lines = [
        f' <DrawingImage x:Key="{key}"><DrawingImage.Drawing><DrawingGroup>',
        f'  <GeometryDrawing Brush="Transparent"><GeometryDrawing.Geometry><RectangleGeometry Rect="0,0,{width:g},{height:g}"/></GeometryDrawing.Geometry></GeometryDrawing>',
        f'  <DrawingGroup ClipGeometry="M 0,0 H {width:g} V {height:g} H 0 Z"><DrawingGroup>',
        f'   <DrawingGroup.Transform><TranslateTransform X="{-x:g}" Y="{-y:g}"/></DrawingGroup.Transform>',
    ]
    for node in root.iter(f"{{{SVG}}}path"):
        # SVG and WPF share these path commands; F1 preserves SVG's nonzero fill rule.
        lines.append(f'   <GeometryDrawing Brush="#111827" Geometry={quoteattr("F1 " + node.get("d"))}/>')
    lines.extend(['  </DrawingGroup></DrawingGroup>', ' </DrawingGroup></DrawingImage.Drawing></DrawingImage>'])
    return "\n".join(lines)


def main():
    entries = [vector(key, ASSETS / filename) for key, filename in FILES.items()]
    dictionary = '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n'
    dictionary += '<!-- Generated by scripts/Generate-BrandAssets.py from the unchanged supplied SVGs. -->\n'
    dictionary += "\n".join(entries) + "\n</ResourceDictionary>\n"
    (ASSETS / "BrandAssets.xaml").write_text(dictionary, encoding="utf-8")

    # A light rounded backing keeps the unchanged dark mark legible on either taskbar theme.
    square = ET.parse(ASSETS / FILES["XiaomaoSquare"]).getroot()
    square.set("x", "0"); square.set("y", "0"); square.set("width", "512"); square.set("height", "512")
    icon_svg = f'<svg xmlns="{SVG}" viewBox="0 0 512 512"><rect x="0" y="0" width="512" height="512" rx="104" fill="#F5F7FB"/>'
    icon_svg += ET.tostring(square, encoding="unicode") + "</svg>"
    (ASSETS / "xa-sk5-app-icon.svg").write_text(icon_svg, encoding="utf-8")
    png = cairosvg.svg2png(bytestring=icon_svg.encode("utf-8"), output_width=512, output_height=512)
    Image.open(BytesIO(png)).save(ASSETS / "xa-sk5.ico", format="ICO", sizes=[(n, n) for n in (16, 20, 24, 32, 40, 48, 64, 96, 128, 256)])
    print("Exported three WPF vector images and a multi-resolution Windows icon.")


if __name__ == "__main__":
    main()
